#!/usr/bin/env python3
"""Regenerate docs/framework-spec.md: a single human-readable file built from the
framework modules and the canonical YAML config. Do not edit the output by hand.

    python tools/build_spec.py
"""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "marketplace-opportunity"
OUT = ROOT / "docs" / "framework-spec.md"

FRONT_MATTER = re.compile(r"^---\n.*?\n---\n", re.S)


def module(path: Path) -> str:
    text = FRONT_MATTER.sub("", path.read_text(encoding="utf-8"), count=1).strip()
    # Demote headings by one level so the spec has a single H1.
    return re.sub(r"^(#+)", r"#\1", text, flags=re.M)


def gates_table() -> str:
    g = yaml.safe_load((SKILL / "config" / "gates.yaml").read_text())["gates"]
    rows = ["| Gate | Name | Fails when | Typical redesign |", "|---|---|---|---|"]
    for gid, v in g.items():
        rows.append(f"| {gid} | {v['name']} | {v['fails_when']} | {', '.join(v['redesign'])} |")
    return "\n".join(rows)


def rubric_tables() -> str:
    r = yaml.safe_load((SKILL / "config" / "rubric.yaml").read_text())
    w = yaml.safe_load((SKILL / "config" / "weights.yaml").read_text())
    bal = w["profiles"][w["default_profile"]]["families"]
    out = []
    for fid, fam in r["families"].items():
        out.append(f"#### {fam['name']} (default weight {bal.get(fid, 0):.0%})\n\n*{fam['question']}*\n")
        out.append("| Criterion | 1 | 3 | 5 |\n|---|---|---|---|")
        for cid, c in r["criteria"].items():
            if c["family"] == fid:
                a = c["anchors"]
                out.append(f"| {c['name']} | {a[1]} | {a[3]} | {a[5]} |")
        out.append("")
    return "\n".join(out)


def profiles_table() -> str:
    w = yaml.safe_load((SKILL / "config" / "weights.yaml").read_text())
    fams = ["structure", "economics", "liquidity", "exposure", "timing", "strategic"]
    rows = ["| Profile | " + " | ".join(fams) + " | Multipliers |", "|---|" + "---|" * (len(fams) + 1)]
    for name, p in w["profiles"].items():
        mult = ", ".join(f"{k} ×{v}" for k, v in (p.get("criterion_multipliers") or {}).items()) or "-"
        rows.append(f"| {name} | " + " | ".join(f"{p['families'][f]:.2f}" for f in fams) + f" | {mult} |")
    return "\n".join(rows)


def main() -> None:
    parts = [
        "<!-- GENERATED by tools/build_spec.py from skills/marketplace-opportunity/. Do not edit by hand. -->\n",
        "# Marketplace opportunity framework: full specification\n",
        "Single-file view for human readers. Agents should load the modular files via "
        "`skills/marketplace-opportunity/SKILL.md` instead.\n",
    ]
    for p in sorted((SKILL / "framework").glob("*.md")):
        parts.append(module(p))
        if p.name.startswith("04-"):
            parts.append("### Gate definitions (from config/gates.yaml)\n\n" + gates_table())
        if p.name.startswith("05-"):
            parts.append("### Rubric anchors (from config/rubric.yaml)\n\n" + rubric_tables())
            parts.append("### Weight profiles (from config/weights.yaml)\n\n" + profiles_table())
    parts.append(module(ROOT / "docs" / "testing-the-framework.md"))
    OUT.write_text("\n\n".join(p.strip() for p in parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(OUT.read_text().split())} words)")


if __name__ == "__main__":
    main()
